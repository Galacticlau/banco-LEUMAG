import { test as probar } from 'node:test';
import verificar from 'node:assert/strict';

/** Prueba de controladores con DOM mínimo; no sustituye una revisión visual en navegador. */
probar('Recorrido: cuenta por tarjeta, acciones docentes, consulta sin débito y salida', async contexto => {
  const eventos = {}, eventosVentana = {};
  const elemento = () => ({ innerHTML: '', textContent: '', open: false, classList: { add() {}, remove() {} }, focus() {}, close() { this.open = false; }, showModal() { this.open = true; } });
  const aplicacion = elemento(), dialogo = elemento(), aviso = elemento();
  const elementos = { '#aplicacion': aplicacion, '#dialogo': dialogo, '#avisos': aviso, '#contenido': elemento(), '#tarjeta-terminal': { value: '2' }, '#premio-terminal': { value: '3' }, '#error-operacion': elemento(), '[name="tarjeta"]': elemento() };
  const originales = new Map(['document','window','location','history','FormData'].map(nombre => [nombre, Object.getOwnPropertyDescriptor(globalThis, nombre)]));
  contexto.after(() => { for (const [nombre, descriptor] of originales) { if (descriptor) Object.defineProperty(globalThis, nombre, descriptor); else delete globalThis[nombre]; } });
  globalThis.document = { querySelector: selector => elementos[selector], addEventListener: (tipo, funcion) => { eventos[tipo] = funcion; } };
  globalThis.window = { scrollTo() {}, addEventListener: (tipo, funcion) => { eventosVentana[tipo] = funcion; } };
  globalThis.location = { hash: '#acceso' };
  globalThis.history = { replaceState: (_estado, _titulo, ruta) => { location.hash = ruta; } };
  globalThis.FormData = class { constructor(formulario) { this.campos = formulario.campos; } get(nombre) { return this.campos[nombre]; } };
  await import('../publico/js/aplicacion.js');
  const ir = ruta => { location.hash = ruta; eventosVentana.hashchange(); };
  const pulsar = (accion, campos = {}) => eventos.click({ target: { closest: () => ({ dataset: { accion, ...campos }, disabled: false }) } });
  const enviar = (id, campos, dataset = {}) => eventos.submit({ preventDefault() {}, target: { id, campos, dataset } });
  verificar.match(aplicacion.innerHTML, /logo-profe.png/);
  ir('#estudiante/ingreso');
  await enviar('formulario-ingreso', { tarjeta: 'DEMO-0002' }); ir(location.hash);
  verificar.match(aplicacion.innerHTML, /Estudiante 02/);
  verificar.doesNotMatch(aplicacion.innerHTML, /href="#docente/);
  verificar.doesNotMatch(aplicacion.innerHTML, /Proyecto de matemática/);
  await pulsar('canjear', { id: '3' });
  verificar.match(dialogo.innerHTML, /no descuenta saldo/);
  verificar.doesNotMatch(dialogo.innerHTML, /data-accion="confirmar-canje"/);
  await pulsar('depositar'); verificar.match(aviso.textContent, /otro espacio/);
  await pulsar('salir'); verificar.doesNotMatch(aplicacion.innerHTML, /Estudiante 02/);
  ir('#docente/ingreso'); await pulsar('entrar-docente'); ir(location.hash);
  verificar.match(aplicacion.innerHTML, /Tus ideas hacen escuela/);
  await pulsar('depositar', { id: '2' });
  verificar.match(dialogo.innerHTML, /value="2" selected/);
  await enviar('formulario-deposito', { estudiante: '2', monto: '200', motivo: 'Razonamiento colaborativo' });
  ir('#docente/terminal'); await pulsar('identificar');
  await pulsar('terminal-canjear'); await pulsar('confirmar-canje', { cuenta: '2', id: '3' });
  verificar.match(dialogo.innerHTML, /Canje aprobado/);
  await pulsar('salir'); ir('#estudiante/ingreso');
  await enviar('formulario-ingreso', { tarjeta: 'DEMO-0002' }); ir(location.hash);
  verificar.match(aplicacion.innerHTML, /900 <small>LC/);
  verificar.match(aplicacion.innerHTML, /Razonamiento colaborativo/);
  ir('#docente/administracion');
  verificar.match(aplicacion.innerHTML, /Abrir demostración docente/);
  verificar.doesNotMatch(aplicacion.innerHTML, /id="filas-cuentas"/);
  ir('#estudiante/ingreso'); await enviar('formulario-ingreso', { tarjeta: 'DEMO-0018' });
  verificar.match(aviso.textContent, /bloqueada/);
  verificar.match(aplicacion.innerHTML, /formulario-ingreso/);
});
